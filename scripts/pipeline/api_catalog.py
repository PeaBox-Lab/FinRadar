def catalog_by_category():
    """Return {category_id: [api, ...]} preserving catalog order."""
    result = {}
    for api in API_CATALOG:
        result.setdefault(api["category"], []).append(api)
    return result


def catalog_summary():
    """Aggregate summary statistics for the Sources page header."""
    total_kpis = sum(a["stats"].get("series_used", 0) for a in API_CATALOG)
    return {
        "total_apis": len(API_CATALOG),
        "total_categories": len(API_CATEGORIES),
        "total_series": total_kpis,
        "open_apis": sum(1 for a in API_CATALOG if "no key" in a["access"].lower() or "open" in a["access"].lower()),
    }
